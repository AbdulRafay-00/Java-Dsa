
// Prim's Algorithm (MST):
// 1. Start from any vertex (node).
// 2. Do not need to sort all edges beforehand.
// 3. Select the minimum-weight edge connecting the current MST to an unvisited vertex.
// 4. Add the selected vertex and edge to the MST.
// 5. Do not create a cycle.
// 6. Repeat until all vertices are connected.
// 7. MST contains exactly V - 1 edges.
// 8. Calculate the total cost by adding all selected edge weights.
